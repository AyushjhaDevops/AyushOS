#include <stdint.h>

#include <kernel/timer.h>
#include <kernel/io.h>
#include <kernel/irq.h>
#include <kernel/pic.h>
#include <kernel/kprintf.h>
#include <kernel/process.h>
/*
 * PIT I/O ports.
 */
#define PIT_CHANNEL0 0x40
#define PIT_COMMAND  0x43

/*
 * PIT command:
 *
 * Bits 7-6:
 *     00 = Channel 0
 *
 * Bits 5-4:
 *     11 = Low byte followed by high byte
 *
 * Bits 3-1:
 *     011 = Mode 3 square wave generator
 *
 * Bit 0:
 *     0 = Binary mode
 */
#define PIT_COMMAND_CHANNEL0 0x36

/*
 * Number of timer interrupts since initialization.
 *
 * volatile is important because this value is modified
 * from interrupt context.
 */
static volatile uint32_t timer_ticks = 0;

/*
 * Actual configured timer frequency.
 */
static uint32_t timer_frequency = PIT_FREQUENCY;

/*
 * IRQ0 handler.
 *
 * IRQ0 is generated by the PIT.
 */
static void timer_irq_handler(irq_frame_t *frame)
{
    (void)frame;

    /*
     * Update global system time.
     */
    timer_ticks++;

    /*
     * Update runtime accounting for the
     * currently running process.
     *
     * No context switch occurs yet.
     */
    process_tick();
}

/*
 * Configure PIT channel 0.
 */
static void pit_set_frequency(uint32_t frequency)
{
    if (frequency == 0)
        return;

    /*
     * Calculate PIT divisor:
     *
     * divisor =
     *     PIT input frequency / desired frequency
     */
    uint32_t divisor = PIT_BASE_FREQUENCY / frequency;

    /*
     * PIT divisor is 16-bit.
     */
    if (divisor < 1)
        divisor = 1;

    if (divisor > 65535)
        divisor = 65535;

    /*
     * Configure PIT channel 0.
     */
    outb(PIT_COMMAND, PIT_COMMAND_CHANNEL0);

    /*
     * Send low byte.
     */
    outb(
        PIT_CHANNEL0,
        (uint8_t)(divisor & 0xFF)
    );

    /*
     * Send high byte.
     */
    outb(
        PIT_CHANNEL0,
        (uint8_t)((divisor >> 8) & 0xFF)
    );
}

/*
 * Initialize timer subsystem.
 */
void timer_initialize(void)
{
    /*
     * Reset tick counter.
     */
    timer_ticks = 0;

    /*
     * Configure frequency.
     */
    timer_frequency = PIT_FREQUENCY;

    /*
     * Register IRQ0 handler.
     */
    irq_register_handler(
        0,
        timer_irq_handler
    );

    /*
     * Program PIT.
     */
    pit_set_frequency(
        timer_frequency
    );

    /*
     * Enable IRQ0 on the PIC.
     */
    pic_clear_mask(0);

    klog_ok(
        "PIT timer initialized"
    );

    klog_info(
        "Timer frequency: 100 Hz"
    );

    klog_info(
        "IRQ0 timer handler registered"
    );
}

/*
 * Return current timer tick count.
 */
uint32_t timer_get_ticks(void)
{
    return timer_ticks;
}

/*
 * Return configured timer frequency.
 */
uint32_t timer_get_frequency(void)
{
    return timer_frequency;
}

/*
 * Return uptime in milliseconds.
 *
 * At 100 Hz:
 *
 *     1 tick = 10 ms
 */
uint32_t timer_get_milliseconds(void)
{
    if (timer_frequency == 0)
        return 0;

    return (
        timer_ticks * 1000U
    ) / timer_frequency;
}

/*
 * Busy-wait delay.
 *
 * This function intentionally consumes CPU time.
 */
void timer_delay_ms(uint32_t milliseconds)
{
    uint32_t start = timer_get_milliseconds();

    while (
        (timer_get_milliseconds() - start)
        < milliseconds
    )
    {
        /*
         * Do nothing.
         *
         * CPU remains active.
         */
        __asm__ volatile ("nop");
    }
}

/*
 * Interrupt-friendly sleep.
 *
 * While sleeping, the CPU executes HLT.
 *
 * The PIT interrupt wakes the CPU approximately
 * every 10 ms.
 */
void timer_sleep_ms(uint32_t milliseconds)
{
    if (milliseconds == 0)
        return;

    uint32_t start = timer_get_milliseconds();

    while (
        (timer_get_milliseconds() - start)
        < milliseconds
    )
    {
        /*
         * Wait for the next hardware interrupt.
         *
         * IRQ0 from the PIT will wake the CPU.
         */
        __asm__ volatile ("hlt");
    }
}
